 await env.DB.prepare('DELETE FROM auth_attempts').bind().run();
 const request=(body,originHeader=origin)=>new Request(origin+'/api/access',{method:'POST',headers:{Origin:originHeader,'Content-Type':'application/json'},body:JSON.stringify(body)});
 assert.equal((await access.POST(request({code:'5678'},'https://attacker.example.test'))).status,403);
 assert.equal((await access.POST(request(null))).status,401);
