test('OAuth enforces consent, exact redirects, S256, resource binding, single-use codes, expiry, refresh rotation and revocation',async()=>{
 assert.equal((oauth.metadata(true).status),200);
 assert.equal((await authorize()).status,200);
 const bad=authParams();bad.set('redirect_uri','https://attacker.example.test');assert.equal((await authorize(bad)).status,400);
 const wrongResource=authParams();wrongResource.set('resource','https://attacker.example.test/mcp');assert.equal((await authorize(wrongResource)).status,400);
 assert.equal((await authorize(authParams(),'POST','5678','https://attacker.example.test')).status,403);
 assert.equal((await authorize(authParams(),'POST','9999')).status,401);
 const consent=await authorize(authParams(),'POST');assert.equal(consent.status,303);
 const location=new URL(consent.headers.get('location'));assert.equal(location.searchParams.get('state'),'synthetic-state');const code=location.searchParams.get('code');
 assert.equal((await exchange({grant_type:'authorization_code',code,redirect_uri:process.env.OAUTH_REDIRECT_URIS,code_verifier:'x'.repeat(43)})).status,400);
 const grant={grant_type:'authorization_code',code,redirect_uri:process.env.OAUTH_REDIRECT_URIS,code_verifier:verifier};
 const granted=await exchange(grant);assert.equal(granted.status,200);const tokens=await granted.json();
 assert.equal((await exchange(grant)).status,400);
 assert.equal(await env.DB.prepare('SELECT token_hash FROM oauth_tokens WHERE token_hash=?').bind(tokens.access_token).first(),null);
 assert.ok(await env.DB.prepare('SELECT token_hash FROM oauth_tokens WHERE token_hash=?').bind(hash(tokens.access_token)).first());
 const init=await (await call(tokens.access_token,'initialize',{protocolVersion:'2025-06-18'})).json();assert.equal(init.result.protocolVersion,'2025-06-18');
 assert.equal((await call('forged')).status,401);
 const saved=await (await call(tokens.access_token,'tools/call',{name:'tracker_log_water',arguments:{amount_ml:250,date:'2026-10-12'}})).json();const entry=JSON.parse(saved.result.content[0].text);
 assert.equal((await env.DB.prepare('SELECT user_id FROM water_intakes WHERE id=?').bind(entry.id).first()).user_id,'synthetic-owner');
 const refreshed=await exchange({grant_type:'refresh_token',refresh_token:tokens.refresh_token});assert.equal(refreshed.status,200);
 assert.equal((await exchange({grant_type:'refresh_token',refresh_token:tokens.refresh_token})).status,400);
 await env.DB.prepare('UPDATE oauth_tokens SET expires_at=0 WHERE token_hash=?').bind(hash(tokens.access_token)).run();assert.equal((await call(tokens.access_token)).status,401);
 const current=await refreshed.json();
 await oauth.token(new Request(origin+'/oauth/revoke',{method:'POST',body:new URLSearchParams({client_id:process.env.OAUTH_CLIENT_ID,client_secret:process.env.OAUTH_CLIENT_SECRET,token:current.access_token})}),true);
 assert.equal((await call(current.access_token)).status,401);
 const invalid=await (await call(current.refresh_token)).json();assert.ok(invalid.error);
});
